"""Exporters for Scriber: Formats output to JSON, Markdown, HTML, SRT, and VTT."""

from __future__ import annotations

import json
from typing import Optional

from scriber.models import ScriberOutput


class ScriberExporter:
    """Formats and exports ScriberOutput into multiple standard file formats."""

    @staticmethod
    def to_txt(output: ScriberOutput) -> str:
        """Generates a clean, beautifully formatted plain text transcript with speaker headers."""
        lines = [
            "=" * 64,
            f"SCRIBER TRANSCRIPT: {output.video_source}",
            f"Duration: {ActionItemFormatter(output.audio_metadata.duration)} | Session: {output.session_id}",
            "=" * 64,
            "",
        ]
        for seg in output.transcription.segments:
            spk = (seg.speaker or "Speaker").replace("_", " ")
            lines.append(f"[{ActionItemFormatter(seg.start)} - {ActionItemFormatter(seg.end)}] {spk}:")
            lines.append(f"{seg.text.strip()}")
            lines.append("")
        return "\n".join(lines)

    @staticmethod
    def to_json(output: ScriberOutput, indent: int = 2) -> str:
        """Serializes output to structured JSON."""
        return json.dumps(output.to_dict(), indent=indent, ensure_ascii=False)

    @staticmethod
    def to_markdown(output: ScriberOutput) -> str:
        """Generates a comprehensive, human-readable Markdown briefing."""
        cs = output.council_analysis
        summary = cs.executive_summary
        trans = output.transcription
        qual = output.quality_report
        val = output.validation_report

        lines = [
            f"# 🎬 Scriber Intelligence Report: {output.video_source}",
            f"> Generated by Scriber v1.0.0 | Session `{output.session_id}` | Duration: {output.audio_metadata.duration:.1f}s",
            "",
            "## 📊 Executive Overview",
            f"### **{summary.headline}**",
            f"{summary.tldr}",
            "",
            "### 🎯 Key Takeaways",
        ]
        for t in summary.key_takeaways:
            lines.append(f"- {t}")

        lines.extend([
            "",
            "### ⚖️ Ratified Decisions",
        ])
        for d in summary.decisions_reached:
            lines.append(f"- ✅ **{d}**")

        lines.extend([
            "",
            "### ❓ Unresolved Inquiries & Blockers",
        ])
        for q in summary.unresolved_questions:
            lines.append(f"- ⚠️ {q}")

        lines.extend([
            "",
            "## 📌 Action Items & Deliverables",
            "| ID | Task | Assignee | Priority | Deadline | Status | Timestamp |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for a in cs.action_items:
            lines.append(
                f"| `{a.id}` | {a.task} | **{a.assignee}** | `{a.priority.upper()}` | {a.due_date or 'TBD'} | `{a.status}` | `{ActionItemFormatter(a.start_time)} - {ActionItemFormatter(a.end_time)}` |"
            )

        lines.extend([
            "",
            "## 💬 Key Points of Discussion",
        ])
        for dp in cs.discussion_points:
            lines.extend([
                f"### {dp.title} (`{ActionItemFormatter(dp.start_time)} - {ActionItemFormatter(dp.end_time)}`)",
                f"- **Summary:** {dp.summary}",
                f"- **Sentiment:** `{dp.sentiment.upper()}` | **Speakers:** {', '.join(dp.speakers)}",
            ])
            if dp.key_quotes:
                lines.append(f"- **Key Quote:** *\"{dp.key_quotes[0]}\"*")
            lines.append("")

        lines.extend([
            "## 📜 Timestamped Full Transcript",
            "",
        ])
        for seg in trans.segments:
            lines.append(
                f"**[{ActionItemFormatter(seg.start)} - {ActionItemFormatter(seg.end)}] ({seg.speaker or 'Speaker'}):** {seg.text}"
            )

        if output.translation:
            lines.extend([
                "",
                "## 🌐 English Translation",
                "",
            ])
            for seg in output.translation.segments:
                lines.append(
                    f"**[{ActionItemFormatter(seg.start)} - {ActionItemFormatter(seg.end)}]:** {seg.text}"
                )

        lines.extend([
            "",
            "## 🛡️ Quality & Accuracy Audit",
            f"- **Confidence Score:** {qual.confidence_avg * 100:.1f}%",
            f"- **Quality Audit:** {qual.overall_score * 100:.1f}%",
            f"- **Repetition Looping Detected:** {'Yes' if qual.repetition_looping_detected else 'No'}",
            f"- **Silence Hallucinations Culled:** {qual.hallucinations_culled}",
            f"- **Word Error Rate (WER):** {val.wer * 100:.2f}%",
            f"- **Net Accuracy Score:** {val.accuracy_score * 100:.2f}% ({'✅ PASSED 99%+ ACCURACY' if val.passed_99_percent else '⚠️ REVIEW NEEDED'})",
            f"- **Validation Certificate:** `{val.certificate_id}`",
            "",
            "---",
            "*Report processed by Scriber autonomous pipeline.*",
        ])

        return "\n".join(lines)

    @staticmethod
    def to_srt(output: ScriberOutput) -> str:
        """Converts transcription segments to standard SubRip (.srt) subtitle format."""
        lines = []
        for idx, seg in enumerate(output.transcription.segments, start=1):
            start_str = format_timestamp_srt(seg.start)
            end_str = format_timestamp_srt(seg.end)
            lines.extend([
                str(idx),
                f"{start_str} --> {end_str}",
                seg.text.strip(),
                "",
            ])
        return "\n".join(lines)

    @staticmethod
    def to_vtt(output: ScriberOutput) -> str:
        """Converts transcription segments to WebVTT (.vtt) subtitle format."""
        lines = ["WEBVTT", ""]
        for idx, seg in enumerate(output.transcription.segments, start=1):
            start_str = format_timestamp_vtt(seg.start)
            end_str = format_timestamp_vtt(seg.end)
            lines.extend([
                str(idx),
                f"{start_str} --> {end_str}",
                seg.text.strip(),
                "",
            ])
        return "\n".join(lines)

